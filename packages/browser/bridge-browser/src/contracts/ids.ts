/**
 * Stride identity primitives: the id layers a browser action must carry.
 *
 * The contract requires every operation to carry explicit
 * identity for the browser instance, connection generation, run control
 * version, tab/frame/document, observation and logical action. Loose strings
 * were enough for a single-connection, single-run prototype; they are not
 * enough once two entry points (desktop + sidebar) and recovery exist, because
 * the failure mode is silent: an action from an old observation, an old
 * connection epoch or an old control revision looks structurally valid.
 *
 * This module therefore uses nominal (branded) types: the runtime value is
 * still a string or number, but a raw value cannot stand in for an id without
 * going through a constructor or parser. Constructors validate the invariants
 * described here, so an invalid id cannot reach the store or the wire.
 *
 * The module is deliberately dependency-free so both the Node bridge plugin
 * and the MV3 extension can import it. It performs no I/O and starts no timer.
 *
 * Observation and element-reference helpers are used by the extension; the
 * run identity and digest rules remain unwired.
 *
 * @module
 */

/** Nominal wrapper: identical at runtime, distinct at compile time. */
export type Branded<T, B extends string> = T & { readonly __brand: B }

/** Identifies one browser installation/profile. Generated by the extension, persisted locally. */
export type BrowserInstanceId = Branded<string, 'BrowserInstanceId'>

/** Monotonic generation of one instance's bridge connection; an older epoch never regains control. */
export type ConnectionEpoch = Branded<number, 'ConnectionEpoch'>

/** Host session that owns the run. */
export type SessionId = Branded<string, 'SessionId'>

/** One Host-arbitrated browser run. */
export type RunId = Branded<string, 'RunId'>

/** Run control version; incremented on target change, pause, stop, takeover and resume. */
export type ControlRevision = Branded<number, 'ControlRevision'>

/** Chrome tab id. */
export type TabId = Branded<number, 'TabId'>

/** Chrome frame id (0 is the top frame). Not interchangeable with a CDP frame id. */
export type FrameId = Branded<number, 'FrameId'>

/** Chrome documentId; changes on cross-document navigation, not on same-document route changes. */
export type DocumentId = Branded<string, 'DocumentId'>

/** One complete observation. A delta observation names its base. */
export type ObservationId = Branded<string, 'ObservationId'>

/** Element reference bound to the observation that produced it. */
export type ElementRef = Branded<string, 'ElementRef'>

/** One logical action, minted by the Host. Transport retries reuse it. */
export type ActionId = Branded<string, 'ActionId'>

/** One transport attempt. A retry keeps the action id and mints a new request id. */
export type RequestId = Branded<string, 'RequestId'>

/** Digest of the immutable action material; disambiguates same-id, different-parameter requests. */
export type RequestDigest = Branded<string, 'RequestDigest'>

const MAX_ID_CHARS = 200

function requireNonEmpty(raw: string, what: string): string {
  if (typeof raw !== 'string') throw new TypeError(`${what} must be a string`)
  const value = raw.trim()
  if (value === '') throw new TypeError(`${what} must not be empty`)
  if (value.length > MAX_ID_CHARS) throw new TypeError(`${what} exceeds ${MAX_ID_CHARS} characters`)
  return value
}

function requireInteger(raw: number, what: string, minimum: number): number {
  if (typeof raw !== 'number' || !Number.isSafeInteger(raw)) throw new TypeError(`${what} must be a safe integer`)
  if (raw < minimum) throw new TypeError(`${what} must be >= ${minimum}`)
  return raw
}

