/** The target an action is allowed to touch, plus the run state it must match. */
export interface TargetScope {
  /** Browser instance the run is bound to. */
  browserInstanceId: BrowserInstanceId
  /** Connection generation the run is bound to. */
  connectionEpoch: ConnectionEpoch
  /** Host session that owns the run. */
  sessionId: SessionId
  /** Run whose control revision is authoritative. */
  runId: RunId
  /** Current control revision of the run. */
  controlRevision: ControlRevision
  /** Tab this action targets. */
  tabId: TabId
  /** Tabs the task may visit; the target must be a member. */
  allowedTabIds: readonly TabId[]
  /** Frame this action targets. */
  frameId: FrameId
  /** Document this action targets. */
  documentId: DocumentId
}

/** The browser-side identity an incoming action actually finds. */
export interface TargetObservation {
  /** Instance the receiving connection belongs to. */
  browserInstanceId: BrowserInstanceId
  /** Epoch of the receiving connection. */
  connectionEpoch: ConnectionEpoch
  /** Revision the run currently has on the Host. */
  controlRevision: ControlRevision
  /** Tab the browser is about to act on. */
  tabId: TabId
  /** Frame the browser is about to act on. */
  frameId: FrameId
  /** Document the browser currently holds for that frame. */
  documentId: DocumentId
}

/** Machine-readable reason a scope check failed. */
export type ScopeViolation =
  | 'instance-mismatch'
  | 'stale-epoch'
  | 'stale-control-revision'
  | 'tab-not-allowed'
  | 'frame-mismatch'
  | 'document-mismatch'

/**
 * Check an in-flight action against the identity the browser actually observes.
 *
 * The Host is authoritative for the scope; this function is the last-mile
 * check the extension performs immediately before a side effect.
 * It reports every violation rather than the first, because the UI must explain
 * all of them and a recovery decision depends on which layer drifted.
 *
 * @param scope - authority recorded for the run.
 * @param observed - identity the browser currently sees.
 * @returns the violations, empty when the action may proceed.
 */
export function validateTargetScope(scope: TargetScope, observed: TargetObservation): ScopeViolation[] {
  const violations: ScopeViolation[] = []
  if (scope.browserInstanceId !== observed.browserInstanceId) violations.push('instance-mismatch')
  if (scope.connectionEpoch !== observed.connectionEpoch) violations.push('stale-epoch')
  if (scope.controlRevision !== observed.controlRevision) violations.push('stale-control-revision')
  if (observed.tabId !== scope.tabId || !scope.allowedTabIds.includes(observed.tabId)) {
    violations.push('tab-not-allowed')
  }
  if (observed.frameId !== scope.frameId) violations.push('frame-mismatch')
  if (observed.documentId !== scope.documentId) violations.push('document-mismatch')
  return violations
}

/**
 * Deterministic JSON serialization used as digest input.
 *
 * `JSON.stringify` is object-key-order dependent, so two hosts could disagree
 * about whether a retried request is "the same". This walks plain data with
 * sorted keys, omits `undefined` members, rejects values that cannot round-trip
 * (functions, symbols, bigints, non-finite numbers, class instances) and
 * detects cycles. Arrays keep their order because it is semantic.
 *
 * @param value - plain JSON-like data.
 * @returns canonical text.
 * @throws TypeError when the value cannot be canonicalized.
 */
export function canonicalize(value: unknown): string {
  return serialize(value, new Set<object>(), 0)
}

const MAX_CANONICAL_DEPTH = 32

function serialize(value: unknown, ancestors: Set<object>, depth: number): string {
  if (depth > MAX_CANONICAL_DEPTH) throw new TypeError('canonicalize: nesting too deep')
  if (value === null) return 'null'
  switch (typeof value) {
    case 'string':
      return JSON.stringify(value)
    case 'boolean':
      return value ? 'true' : 'false'
    case 'number':
      if (!Number.isFinite(value)) throw new TypeError('canonicalize: non-finite number')
      return JSON.stringify(value)
    case 'object':
      break
    default:
      throw new TypeError(`canonicalize: unsupported ${typeof value}`)
  }
  const object = value as object
  if (ancestors.has(object)) throw new TypeError('canonicalize: cyclic value')
  ancestors.add(object)
  try {
    if (Array.isArray(object)) {
      const items: string[] = []
      for (const item of object) items.push(serialize(item, ancestors, depth + 1))
      return `[${items.join(',')}]`
    }
    const prototype = Object.getPrototypeOf(object)
    if (prototype !== Object.prototype && prototype !== null) {
      throw new TypeError('canonicalize: non-plain object')
    }
    const entries: string[] = []
    for (const key of Object.keys(object as Record<string, unknown>).sort()) {
      const member = (object as Record<string, unknown>)[key]
      if (member === undefined) continue
      entries.push(`${JSON.stringify(key)}:${serialize(member, ancestors, depth + 1)}`)
    }
    return `{${entries.join(',')}}`
  } finally {
    ancestors.delete(object)
  }
}

/** Immutable material a logical action is authorized by; the digest is computed over this. */
export interface ActionDigestMaterial {
  /** Logical action id. */
  actionId: ActionId
  /** Instance the action targets. */
  browserInstanceId: BrowserInstanceId
  /** Tab the action targets. */
  tabId: TabId
  /** Frame the action targets. */
  frameId: FrameId
  /** Document the action targets. */
  documentId: DocumentId
  /** Control revision the action was authorized under. */
  controlRevision: ControlRevision
  /** Action name, e.g. `browser_click`. */
  name: string
  /** Action arguments. */
  args: Record<string, unknown>
  /** Observation the action was planned from, when one was required. */
  beforeObservationId?: ObservationId
}

/**
 * Compute the digest that binds one logical action to its target, parameters,
 * pre-observation and control revision.
 *
 * Any of those changing mints a new action; a transport retry keeps the id and
 * therefore the digest. A same-id request with a different digest is a
 * protocol violation the Host must reject.
 *
 * Uses WebCrypto so the same implementation runs in Node and in the MV3
 * service worker.
 *
 * @param material - immutable action material.
 * @returns lowercase hex SHA-256 digest.
 */
export async function computeRequestDigest(material: ActionDigestMaterial): Promise<RequestDigest> {
  const bytes = new TextEncoder().encode(canonicalize(material))
  const hash = await globalThis.crypto.subtle.digest('SHA-256', bytes)
  const hex = Array.from(new Uint8Array(hash), byte => byte.toString(16).padStart(2, '0')).join('')
  return hex as RequestDigest
}
