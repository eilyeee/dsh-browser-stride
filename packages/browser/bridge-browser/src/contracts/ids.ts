/**
 * Build an observation-bound element reference.
 *
 * A bare inventory index is transient: the same number addresses a different
 * element after a re-render. Encoding the observation id makes the binding
 * explicit so the extension can reject a stale reference instead of clicking
 * whatever now occupies that index.
 *
 * @param observationId - observation that produced the reference.
 * @param index - inventory index within that observation.
 * @returns the branded reference, `<observationId>:<index>`.
 */
export function makeElementRef(observationId: ObservationId, index: number): ElementRef {
  const slot = requireInteger(index, 'element index', 0)
  return `${observationId}:${slot}` as ElementRef
}

/**
 * Split an element reference back into its observation binding.
 * @param ref - candidate reference.
 * @returns the parsed parts, or `undefined` when the reference is malformed.
 */
export function parseElementRef(ref: ElementRef | string): { observationId: ObservationId; index: number } | undefined {
  if (typeof ref !== 'string') return undefined
  const separator = ref.lastIndexOf(':')
  if (separator <= 0 || separator === ref.length - 1) return undefined
  const observationPart = ref.slice(0, separator)
  if (observationPart.length > MAX_ID_CHARS || observationPart.trim() !== observationPart || observationPart === '') return undefined
  const indexPart = ref.slice(separator + 1)
  if (!/^\d+$/.test(indexPart)) return undefined
  const index = Number(indexPart)
  if (!Number.isSafeInteger(index) || index < 0) return undefined
  return { observationId: asObservationId(observationPart), index }
}

/**
 * Does this reference belong to the given observation?
 * @param ref - candidate reference.
 * @param observationId - observation the caller intends to act on.
 * @returns true only when the reference was minted by that observation.
 */
export function isElementRefOf(ref: ElementRef | string, observationId: ObservationId): boolean {
  const parsed = parseElementRef(ref)
  return parsed !== undefined && parsed.observationId === observationId
}

